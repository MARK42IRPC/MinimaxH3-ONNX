_BY_ID = {item.id: item for item in DOWNLOAD_COMPONENTS}


def component_by_id(component_id: str) -> DownloadComponent:
    try:
        return _BY_ID[component_id]
    except KeyError as exc:
        raise ValueError(f"Unknown model component: {component_id}") from exc


def _manifest_status(directory: Path) -> dict[str, Any]:
    manifest_path = directory / "manifest.json"
    if not manifest_path.is_file():
        return {"status": "missing", "manifest": False, "missing_files": []}
    try:
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        return {"status": "invalid", "manifest": True, "error": str(exc), "missing_files": []}
    graphs = manifest.get("graphs", [])
    missing = [str(item) for item in graphs if not (directory / str(item)).is_file()]
    # Some manifests use a block list while graph names are generated by the
    # exporter. The declared graph references remain the authoritative check.
    valid = manifest.get("validation_passed") is True
    if missing:
        status = "incomplete"
    elif not valid:
        status = "unvalidated"
    else:
        status = "ready"
    files = list(directory.rglob("*")) if directory.is_dir() else []
    size = sum(item.stat().st_size for item in files if item.is_file())
    return {
        "status": status,
        "manifest": True,
        "validation_passed": valid,
        "missing_files": missing,
        "graph_count": len(graphs),
        "size_bytes": size,
    }


def component_status(workspace: Path, item: DownloadComponent) -> dict[str, Any]:
    directory = workspace / item.relative_path
    if item.id == "tokenizer":
        required = ("tokenizer.json", "tokenizer_config.json", "vocab.json", "merges.txt")
        missing = [name for name in required if not (directory / name).is_file()]
        files = [directory / name for name in required if (directory / name).is_file()]
        size = sum(path.stat().st_size for path in files)
        return {**item.to_dict(), "status": "ready" if not missing else "incomplete", "manifest": False, "missing_files": missing, "size_bytes": size}
    return {**item.to_dict(), **_manifest_status(directory)}


def all_component_status(workspace: Path) -> list[dict[str, Any]]:
    return [component_status(workspace, item) for item in DOWNLOAD_COMPONENTS]
