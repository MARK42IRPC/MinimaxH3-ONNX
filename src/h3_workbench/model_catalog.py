@dataclass(frozen=True)
class DownloadComponent:
    id: str
    label: str
    relative_path: str
    include: tuple[str, ...]
    role: str
    required_for_generation: bool = False

    def to_dict(self) -> dict[str, Any]:
        return {
            "id": self.id,
            "label": self.label,
            "relative_path": self.relative_path,
            "role": self.role,
            "required_for_generation": self.required_for_generation,
        }


